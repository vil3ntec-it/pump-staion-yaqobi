    ///     ۲۰۰ ردیف → ۱٬۴۷۴ ms      ← دیگر نه
    ///
    /// پس سقف ماند ولی جایش عوض شد: دیگر «یک صفحه» نیست، **صد ردیف** است.
    /// هیچ ماهِ واقعیِ این پمپ به صد ردیف نمی‌رسد، پس عملاً سقفی دیده
