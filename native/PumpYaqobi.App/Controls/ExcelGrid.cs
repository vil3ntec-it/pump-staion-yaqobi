    {
        get => GetValue(GrowsToContentProperty);
        set => SetValue(GrowsToContentProperty, value);
    }

    /// <summary>
    /// ══ «دیوار» — ستون‌ها هرگز از کادرِ خودِ جدول بیرون نمی‌زنند ════════════
    ///
    /// گزارشِ صاحب ریپو با عکس (۱۴۰۵/۰۷/۱۲): «اون یادداشت و این دو کادرِ نوع و
    /// واحد رو ببین، از جدول‌ها بیرون نشن… دیوارشونو بزار.»
    ///
    /// روشن باشد ⇒ پهنای **ذخیره‌شده** هم اگر در این قاب جا نشد کوچک می‌شود
    /// (اول ستون‌های نوشته‌ای، عدد تا آخرین چاره نه)، و ستونی که کاربر پهن
    /// کشید جا را از ستون‌های **دیگر** می‌گیرد، نه از بیرونِ جدول.
    ///
    /// ⛔ **از ۱۴۰۵/۰۷/۱۶ برای همهٔ جدول‌ها پیش‌فرض است.** خواستهٔ صریحِ صاحب ریپو:
    /// «بعضی بخش‌ها کادرِ جدولشان خیلی بزرگ می‌شود… هیچ کادری نباید از جدول‌ها
    /// کاربر را به چپ یا راست هدایت کند.» پس خواستهٔ قدیمیِ «ستونِ کشیده‌شده اگر
    /// بزرگ شد به چپ و راست اسکرول شود» پس گرفته شد: ستونی که کاربر پهن کشید جا
    /// را از ستون‌های دیگرِ همان جدول می‌گیرد. ⛔ به ‎false‎ برنگردانید.
    /// ⚠️ پهنای ذخیره‌شدهٔ کاربر **روی دیسک دست نمی‌خورد**: فقط در این قاب
    /// کوچک نشان داده می‌شود، پس روی نمایشگرِ بزرگ‌تر همان پهنای خودش برمی‌گردد.
    /// </summary>
    public static readonly StyledProperty<bool> KeepInsideProperty =
        AvaloniaProperty.Register<ExcelGrid, bool>(nameof(KeepInside), defaultValue: true);

    public bool KeepInside
    {
        get => GetValue(KeepInsideProperty);
        set => SetValue(KeepInsideProperty, value);
    }

    /// <summary>
    /// ══ پهنای ستون‌ها یک بار تنظیم شود، همه‌جا بماند ════════════════════════
    ///
    /// گزارشِ صاحب ریپو: «وقتی جدولِ یک ورق را تنظیم می‌کنم، تمامِ جدول‌های
    /// همهٔ ورق‌ها برابر بشوند… نمی‌شود که هر روز من اندازه‌ها را درست کنم.»
    ///
    /// جدولی که این کلید را داشته باشد، پهنای دستیِ کاربر را در تنظیماتِ
    /// برنامه می‌گذارد و هر جدولِ دیگری با همان کلید — ورقِ فردا هم — همان را
    /// برمی‌دارد. خالی یعنی «یادت نماند»، پیش‌فرضِ همهٔ جدول‌های دیگر.
    ///
    /// ⚠️ کلید باید به **ستون‌ها** بسته باشد نه به دادهٔ ردیف‌ها: دو جدولِ
    /// تراکنشِ ورق ستون‌های یکسان دارند و عمداً یک کلید می‌گیرند، تا چپ و
    /// راست هم‌اندازه بمانند.
    /// </summary>
    public static readonly StyledProperty<string?> WidthKeyProperty =
        AvaloniaProperty.Register<ExcelGrid, string?>(nameof(WidthKey));

