using Avalonia.Controls;
using Avalonia.Input;
using Avalonia.VisualTree;

namespace PumpYaqobi.App.Controls;

/// <summary>
/// ══ کارتِ تنظیماتِ صفحهٔ چاپ ══════════════════════════════════════════════
///
/// همان ‎.xcard‎ی سایت: نشانه، عنوانِ پررنگ و یک خطِ توضیح — و یک کشوی واقعی
/// پشتش.
///
/// ⚠️ تنها فرقش با ‎ComboBox‎ همین است که **چرخِ ماوس مقدارش را عوض نمی‌کند**.
///
/// گزارشِ صاحب ریپو: «روی هر کادر که می‌روم با اسکرول تغییر می‌کنند؛ این دیگه
/// چیه؟ باید با کلیک روی هر کدام بتوانم تغییر بدهم.»
///
/// حق داشت و ریشه‌اش هم پیدا شد: خودِ ‎ComboBox‎ی آوالونیا این کار را می‌کند
/// (‎ComboBox.OnPointerWheelChanged‎ — وقتی فوکوس دارد و کشویش بسته است،
/// ‎SelectNext/SelectPrevious‎ می‌زند). یعنی کاربر می‌خواست ستون را بلغزاند و
/// به‌جایش کاغذ از A4 به A5 می‌پرید — بی آن‌که بفهمد.
///
/// این‌جا آن رفتار **کاملاً** برداشته می‌شود: ‎base‎ صدا زده نمی‌شود و رویداد
/// هم ‎Handled‎ نمی‌شود، پس بی هیچ دست‌کاری به ستونِ لغزنده می‌رسد و همان‌طور
/// که کاربر انتظار دارد صفحه می‌لغزد. عوض کردنِ مقدار فقط با کلیک است.
/// </summary>
public class SettingCard : ComboBox
{
    /// <summary>سبک و قالبِ خودِ ‎ComboBox‎ — این کنترل فقط رفتار را عوض می‌کند.</summary>
    protected override Type StyleKeyOverride => typeof(ComboBox);

    protected override void OnPointerWheelChanged(PointerWheelEventArgs e)
    {
        // ⚠️ عمداً هیچ — نه ‎base‎، نه ‎e.Handled = true‎.
        //
        // ‎base‎ مقدار را عوض می‌کند (همان باگ)، و ‎Handled‎ کردن جلوی لغزیدنِ
        // ستون را می‌گرفت. با هیچ‌کدام، رویداد دست‌نخورده بالا می‌رود و
        // ‎ScrollViewer‎ی ستون کارِ همیشگی‌اش را می‌کند.
        //
        // کشوی **باز** استثناست: آن‌جا چرخاندن یعنی گشتن در فهرست، که درست
        // است — ولی آن را هم خودِ فهرستِ بازشده انجام می‌دهد، نه این کنترل.
    }
}
