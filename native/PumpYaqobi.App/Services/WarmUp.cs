using PumpYaqobi.App.ViewModels;

namespace PumpYaqobi.App.Services;

/// <summary>
/// ══ یک بار، پشتِ پردهٔ لودینگ ════════════════════════════════════════════════
///
/// خواستهٔ صاحب ریپو:
///
///   «موقعِ تازه باز کردنِ اپ باید یک لودینگ داشته باشه تا همهٔ بخش‌ها و
///    برنامه رو رندر کنه؛ بعدش که شد، این بازگشت به صفحهٔ اصلی نباید تأخیری
///    داشته باشه… جوری نباشه با هر بار رندر شدن، اپ حافظه اضافه کنه… و روی
///    هیچ کامپیوتر ضعیف و قوی سنگین نباشه.»
///
/// سه بندِ همان جمله، سه قاعدهٔ این فایل:
///
///   ۱) **همهٔ بخش‌ها** — برنامه پشتِ پرده واقعاً در هر بخش می‌گردد: داده‌اش
///      خوانده می‌شود، صفحه‌اش ساخته و چیده می‌شود، و صفحهٔ درونی‌اش (ورق،
///      حسابِ شخص) هم یک بار باز و بسته می‌شود.
///   ۲) **بی تأخیرِ بازگشت** — ‎ViewLocator‎ همان نمونه را کش می‌کند، پس کلیکِ
///      بعدیِ کاربر همان صفحهٔ گرم را می‌گیرد.
///   ۳) **بی رشدِ حافظه** — هیچ صفحه‌ای این‌جا ساخته نمی‌شود که بعداً دور
///      انداخته شود، و گرم کردن یک بار در عمرِ برنامه اجرا می‌شود
///      (<see cref="Done"/>).
///
/// ⚠️ و چرا «واقعاً در هر بخش می‌گردد» و نه یک قابِ کناری: یک بار صفحه‌ها را
/// در یک ‎ContentControl‎ی جدا می‌چیدیم و ورق باز هم بارِ اولش ۲ ثانیه بود.
/// چیزی که در جای واقعی‌اش چیده نشده، گرم نشده. (و بدتر: قابی که اصلاً در
/// درختِ بصری نباشد، ‎UpdateLayout()‎ش هیچ کاری نمی‌کند و گرم کردن فقط ادایش
/// را درمی‌آورد.)
///
/// ⚠️ «سنگین نباشد»: بینِ هر بخش نوبت به رابط پس داده می‌شود، پس نه نخ قفل
/// می‌شود و نه انیمیشنِ لودینگ می‌پرد. روی کامپیوترِ کند فقط شمارنده آرام‌تر
/// بالا می‌رود.
/// </summary>
public sealed class WarmUp
{
    /// <summary>گرم کردن یک بار در عمرِ برنامه — نه با هر ورود و خروج.</summary>
    public bool Done { get; private set; }

    /// <summary>چند بخش گرم شد — برای نوشتهٔ زیرِ انیمیشن و برای آزمون.</summary>
    public int Warmed { get; private set; }

    public async Task RunAsync(
        IReadOnlyList<SectionViewModel> sections,
        Func<SectionViewModel, Task> visit,
        Action<double, string> report)
    {
        if (Done) return;
        Done = true;

        var n = sections.Count;
        for (var i = 0; i < n; i++)
        {
            var sec = sections[i];
            report((double)(i + 1) / n, sec.Title);

            try { await visit(sec); }
            catch
            {
                // گرم کردن یک تجمل است. بخشی که سرِ باز شدن گیر کرد، سرِ
                // کلیکِ کاربر هم همان‌جا گیر می‌کند — و این‌جا نباید جلوی
                // باز شدنِ برنامه را بگیرد.
            }

            Warmed++;
        }

        report(1, "");
    }
}
