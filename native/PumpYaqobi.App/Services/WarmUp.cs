using Avalonia;
using Avalonia.Controls;
using Avalonia.Layout;
using Avalonia.Threading;
using PumpYaqobi.App.ViewModels;

namespace PumpYaqobi.App.Services;

/// <summary>
/// ══ گرم کردن، بی آن‌که کسی جایی برود ════════════════════════════════════════
///
/// گزارشِ صاحب ریپو: «هنگام اجرای لودینگ، کاربر به بخش‌های مختلف برنامه منتقل
/// می‌شود، صفحات مختلف نمایش داده می‌شوند و در نهایت دوباره به صفحه قفل
/// برمی‌گردد. این رفتار کاملاً اشتباه است.»
///
/// حق داشت، و ریشه همین‌جا بود: نسخهٔ پیشین با ‎GoAsync‎ واقعاً در بخش‌ها
/// **می‌گشت** و فقط به پرده تکیه می‌کرد — پرده‌ای که اتفاقاً شفاف هم بود
/// (‎Pump.Bg‎ی نبوده). یعنی هم مسیر عوض می‌شد، هم صفحه‌های محافظت‌شده پیش از
/// احراز هویت ساخته و دیده می‌شدند.
///
/// حالا هیچ مسیری عوض نمی‌شود. صفحه‌ها فقط در یک **قابِ نادیدنیِ پشتِ پرده**
/// چیده می‌شوند:
///
///   • ‎Current‎ دست نمی‌خورد، ‎LastSection‎ دست نمی‌خورد، هیچ ناوبری‌ای رخ
///     نمی‌دهد.
///   • چون هنوز وارد نشده‌ایم، هیچ دادهٔ محافظت‌شده‌ای در این صفحه‌ها نیست —
///     فقط قالب و سبک و ساختارشان ساخته می‌شود، که همان گران‌ترین بخش است.
///   • دادهٔ بخش‌ها بعد از رمز و بی‌صدا گرم می‌شود
///     (<see cref="MainViewModel.WarmDataAsync"/>).
///
/// ⚠️ و چیدن در جای **دائمیِ** خودِ نما انجام می‌شود، نه در یک قابِ موقت: با
/// برداشته شدن از قابِ موقت، نما از درختِ بصری جدا می‌شود و ‎DataGrid‎ همهٔ
/// ردیف‌هایش را دور می‌اندازد — یعنی گرم کردن همان لحظه باطل می‌شود. سنجیده
/// شد: با قابِ موقت ۱٬۴۷۵ میلی‌ثانیه، در برابرِ ۵۳ی دفعه‌های بعد.
///
/// پس پوستهٔ برنامه حینِ لودینگ **چیده** می‌شود ولی دیده نمی‌شود: پردهٔ مات
/// رویش است و هیچ‌چیزی از زیرش پیدا نیست.
/// </summary>
public sealed class WarmUp
{
    /// <summary>گرم کردن یک بار در عمرِ برنامه — نه با هر ورود و خروج.</summary>
    public bool Done { get; private set; }

    /// <summary>
    /// گذرِ دومِ داده، پس از رمز. پیش از ورود هیچ اجازه‌ای نداریم، پس مسیرِ
    /// داده همان یک بارِ گرانش را بعد از احراز هویت می‌دهد.
    /// </summary>
    public bool DataDone { get; private set; }

    public void MarkDataDone() => DataDone = true;

    /// <summary>چند صفحه گرم شد — برای نوشتهٔ زیرِ انیمیشن و برای آزمون.</summary>
    public int Warmed { get; private set; }

    public async Task RunAsync(
        IReadOnlyList<SectionViewModel> sections,
        ViewLocator locator,
        Action layout,
        Action<double> report)
    {
        if (Done) return;
        Done = true;

        var n = sections.Count;
        for (var i = 0; i < n; i++)
        {
            var sec = sections[i];
            report((double)(i + 1) / n);

            try
            {
                // نما ساخته می‌شود و در جای **دائمیِ** خودش می‌نشیند
                locator.Build(sec);

                // ⚠️ و همان‌جا چیده می‌شود، نه در یک قابِ موقت. یک بار قابِ
                // موقت گذاشتیم و کار نکرد (۲٬۱۰۶ ⇐ ۱٬۴۷۵ میلی‌ثانیه، در برابرِ
                // ۵۳ی دفعه‌های بعد): با برداشته شدن از قاب، نما از درختِ بصری
                // **جدا** می‌شود و ‎DataGrid‎ همهٔ ردیف‌های ساخته‌شده‌اش را دور
                // می‌اندازد. یعنی گرم کردن همان لحظه باطل می‌شد.
                //
                // ⚠️ این «ناوبری» نیست و نباید با آن اشتباه شود: ‎Current‎ عوض
                // نمی‌شود، ‎LastSection‎ نوشته نمی‌شود، دادهٔ هیچ بخشی خوانده
                // نمی‌شود، و همهٔ این‌ها زیرِ پردهٔ **مات**ِ لودینگ می‌گذرد.
                // چیزی که اشتباه بود و برداشته شد، ‎GoAsync‎ بود.
                sec.IsShown = true;
                layout();

                // صفحهٔ درونیِ بخش، اگر دارد (ورق، …) — با دادهٔ ساختگیِ خودش
                sec.WarmInner(layout);

                sec.IsShown = false;
                layout();
            }
            catch
            {
                // گرم کردن یک تجمل است و نباید هیچ‌وقت جلوی باز شدنِ برنامه
                // را بگیرد.
                try { sec.IsShown = false; } catch { }
            }

            Warmed++;

            // نوبت را پس بده تا انیمیشنِ پرده بچرخد و پنجره جواب بدهد
            await Dispatcher.UIThread.InvokeAsync(() => { }, DispatcherPriority.Background);
        }

        report(1);
    }
}
