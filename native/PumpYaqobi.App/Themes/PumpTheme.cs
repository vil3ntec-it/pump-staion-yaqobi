using Avalonia;
using Avalonia.Media;

namespace PumpYaqobi.App.Themes;

/// <summary>
/// ══ تم‌های برنامه ══════════════════════════════════════════════════════════
/// دو تمی که صاحب ریپو از روی دو عکسِ نمونه انتخاب کرد — نه یکی بیشتر، نه کمتر:
///   blue   «آبیِ روشن»   روشن — لایت مود، بومِ سفیدِ خالص
///   gold   «مشکی و زرد»  تیره — دارک مود، بومِ #0B0B0F و تاکیدِ #FFD700
///
/// مرمرِ شرابی، اُبسیدین و پنج نمونهٔ میانی همه برداشته شدند (۱۴۰۵/۰۶/۲۵).
///
/// ⚠️ سه قاعده‌ای که این پالت‌ها را «گران‌قیمت» می‌کند و نباید شکسته شود:
///   ۱) رنگِ تاکید خسیس خرج می‌شود — تبِ فعال، دکمهٔ اصلی، عددهای کلیدی. بس.
///   ۲) هر سطح با یک خطِ نازک و یک پلهٔ روشناییِ کم جدا می‌شود، نه با رنگِ پررنگ.
///   ۳) هیچ سایه و گرادیانی روی چیزهای تکرارشونده (کارت، ردیف) نمی‌نشیند —
///      در Avalonia هر سایه یک لایهٔ رندرِ جداست و صدتا از آن، بخش را کند می‌کند.
///      برای همین این‌جا گرادیان فقط برای سربرگ/نوار/دکمهٔ اصلی تعریف شده است.
///
/// ⚠️ قاعدهٔ چهارم که با گزارشِ «کادرها دیده نمی‌شوند» اضافه شد:
///
///     هر کارت باید **هم** از بوم پله بخورد **هم** لبه‌اش از خودش جدا باشد.
///
/// پیش از این مرمر بومِ ‎#f3f1f1‎ داشت و کارتِ سفید: پلهٔ ۰٫۰۵۳ که روی نمایشگرِ
/// روشن اصلاً دیده نمی‌شد، و لبهٔ ‎#e2dcdc‎ هم یک خطِ محوِ ۰٫۱۳. گزارشِ صاحب
/// ریپو دقیقاً همین بود: «کادرها با بک‌گراند تفاوت رنگ ندارن، فقط یک خط نازک
/// دارن که اونو هم ندارن — هیچ‌کدوم دیده نمی‌شد، حتی خودِ جدول‌ها.»
///
/// حالا بوم ‎#e9e5e5‎ است (پلهٔ ۰٫۰۹۹) و لبه ‎#d5cacb‎ (رِیمِ ۰٫۱۹۸). در تمِ تیره
/// همان دو شرط با لبهٔ ‎#333b63‎ برقرار است. ‎LookAudit‎ این را قفل کرده — هر
/// پالتِ تازه‌ای که از آستانه پایین‌تر بیفتد، سنجش قرمز می‌شود.
///
/// «نور پس‌زمینه» (hexfx/atmo) عمداً وجود ندارد — پاک شده و برنمی‌گردد.
/// </summary>
public sealed record PumpTheme(
    string Id,
    string Title,
    bool IsDark,
    Color Dark,        // بومِ صفحه
    Color Panel,       // سطحِ پنل
    Color Card,        // سطحِ کارت/جدول
    Color Border,
    Color Text,
    Color Muted,
    Color Label,
    Color Accent,
    Color OnAccent,
    Color HeaderTitle,
    Color ChromeBorder,
    Color HeadBand,    // نوارِ سرِ جدول و ردیفِ «جمله»
    Color OnHeadBand,  // نوشتهٔ روی همان نوار
    Color[] HeaderBg,   // گرادیانِ افقیِ سربرگ
    Color[] BannerBg,
    Color[] NavBg,
    Color[] AppBg,      // گرادیانِ عمودیِ بوم
    Color[] AccentGrad, // گرادیانِ دکمه‌های اصلی
    Color? Section = null, // بدنهٔ کادرِ بخش — بینِ بوم و کارت (پیش‌فرض: پنل)
    Color? Input = null,   // کادرِ تایپ (پیش‌فرض: مخلوطِ پنل و بوم)
    Color[]? NavActiveBg = null, // زمینهٔ تبِ فعالِ نوار (پیش‌فرض: AccentGrad)
    Color? NavActiveFg = null,   // نوشتهٔ تبِ فعال (پیش‌فرض: OnAccent)
    string CardShadow = "",      // نورِ لبه + سایهٔ کارت (BoxShadows)
    string CardShadowHover = "", // همان، کمی پررنگ‌تر زیرِ ماوس
    bool FlatCanvas = false)     // بوم و کارت عمداً هم‌رنگ‌اند؛ جدایی از سایه و خط می‌آید
{
    /// <summary>
    /// ══ سه طبقه، نه دو ═══════════════════════════════════════════════════════
    /// گزارشِ صاحب ریپو با عکس (۱۴۰۵/۰۶/۲۵): «کادرهای آبی که کشیدم باید متفاوت
    /// باشن با اون جاهای خالیِ بغلِ کادر… برای همه جای برنامه همین مشکل است.»
    ///
    /// ریشه: هر بخش یک کادرِ بزرگ است (‎SectionPage‎، رنگِ ‎Card‎) و داخلش
    /// کادرهای کوچک (‎.panel‎ / ‎.stat‎، رنگِ ‎Panel‎) و کادرِ تایپ (‎TextBox‎،
    /// باز هم ‎Panel‎). در تمِ روشن هر سه سفید بودند، پس «جای خالیِ بغلِ کادر»
    /// و خودِ کادر یک رنگ می‌شد و فقط یک خطِ نازک می‌ماند.
    ///
    ///     بوم (Dark)  <  بدنهٔ بخش (Section)  <  کارتِ داخلی (Panel/Card)  <  کادرِ تایپ (Input)
    ///
    /// ‎Section‎ همین‌جا در پالت می‌نشیند و ‎Input‎ در ‎ThemeManager‎ از پنل و بوم
    /// مخلوط می‌شود. ‎LookAudit‎ هر سه پله را می‌سنجد.
    /// </summary>
    public Color SectionBg => Section ?? Panel;

    public static Color C(string hex) => Color.Parse(hex);

    // ══ دو تم — لایتِ آبی و دارکِ مشکی‌وزرد (۱۴۰۵/۰۶/۲۵) ═══════════════════════
    // خواستهٔ صاحب ریپو با دو عکسِ مرجع و پالتِ دقیق:
    //   لایت:  #1E3A8A آبیِ تیره (تاکید/انتخاب) · #3B82F6 آبیِ اصلی (دکمه، نمودار، آیکون)
    //          #60A5FA آبیِ روشن (نورِ لبه، نقطهٔ نمودار) · #E0F2FE سطوحِ ملایم · #FFFFFF بوم
    //   دارک:  #0B0B0F بوم · #1A1A1F کارت · #FFD700 تاکید · #E6C800 خطِ لبه · #FFF3C4 هایلایت
    //
    // «افکتِ نور دورِ کادرها — اولویتِ بسیار مهم: خطِ باریکِ آبی روی لبه، هالهٔ
    //  نورِ بسیار ملایم نزدیکِ لبه با #60A5FA، و سایهٔ تیره بیرونِ کادر… نور
    //  نباید هالهٔ بزرگ و شدید باشد.» ⇒ ‎CardShadow‎: چهار لایهٔ BoxShadow —
    //  هایلایتِ سفیدِ داخلی (فقط دارک)، خطِ ۱ پیکسلیِ آبی، هالهٔ ۷ پیکسلیِ کم‌آلفا،
    //  و سایهٔ بیرونی. زیرِ ماوس همان با کمی شدتِ بیشتر (‎CardShadowHover‎).
    //
    // ⚠️ بومِ لایت عمداً سفیدِ خالص است و کارت هم سفید («نمی‌خواهم پس‌زمینهٔ
    //  اصلی خاکستری یا آبیِ روشن شود»). جدایی از خطِ آبیِ ملایم و سایهٔ روشن
    //  می‌آید، نه از پلهٔ روشنایی؛ ‎FlatCanvas‎ همین را به ‎LookAudit‎ می‌گوید.

    /// <summary>«آبیِ روشن» — لایت مود: بومِ سفیدِ خالص، کارتِ سفید با لبهٔ آبیِ ظریف و سایهٔ روشن.</summary>
    public static readonly PumpTheme Blue = new(
        "blue", "آبیِ روشن", false,
        C("#ffffff"), C("#ffffff"), C("#ffffff"), C("#b9d3f5"),
        C("#0b1f3a"), C("#5b6b80"), C("#1e3a8a"), C("#3b82f6"), C("#ffffff"),
        C("#1e3a8a"), C("#b9d3f5"),
        C("#e0f2fe"), C("#1e3a8a"),
        new[] { C("#ffffff"), C("#ffffff"), C("#ffffff") },
        new[] { C("#fbfdff"), C("#ffffff"), C("#fbfdff") },
        new[] { C("#ffffff"), C("#ffffff"), C("#ffffff") },
        new[] { C("#ffffff"), C("#ffffff"), C("#fdfeff"), C("#fafcff") },
        new[] { C("#60a5fa"), C("#3b82f6"), C("#2563eb") },
        Section: C("#f6f9fe"),
        Input: C("#f3f8fe"),
        NavActiveBg: new[] { C("#e0f2fe"), C("#dbeafe"), C("#e0f2fe") },
        NavActiveFg: C("#1e3a8a"),
        CardShadow: "0 0 0 1 #2660A5FA, 0 1 2 0 #140B1F3A, 0 4 12 0 #121E3A8A",
        CardShadowHover: "0 0 0 1 #5560A5FA, 0 0 6 0 #3360A5FA, 0 6 16 0 #1A1E3A8A",
        FlatCanvas: true);

    /// <summary>
    /// «مشکی و زرد» — دارک مود (عکسِ مرجعِ صاحب ریپو، ۱۴۰۵/۰۶/۲۵؛ «اون قبلیه [سرمه‌ای]
    /// اشتباه شد»): بومِ ‎#0B0B0F‎، کارتِ خاکستریِ تیره نزدیکِ ‎#1A1A1F‎، تاکیدِ
    /// ‎#FFD700‎، خطِ لبه ‎#E6C800‎ کم‌آلفا، هالهٔ طلاییِ ظریف، هایلایتِ ‎#FFF3C4‎ی
    /// بسیار کم روی لبهٔ داخلی و سایهٔ مشکیِ بیرونی. در تیرگی هر طبقه روشن‌تر
    /// از زیرش است، وگرنه سوراخ دیده می‌شود نه کادر.
    /// </summary>
    public static readonly PumpTheme Gold = new(
        "gold", "مشکی و زرد", true,
        C("#0b0b0f"), C("#1e1e24"), C("#212127"), C("#4a4322"),
        C("#f5f3e8"), C("#a9a79a"), C("#ffe066"), C("#ffd700"), C("#0b0b0f"),
        C("#fff3c4"), C("#4a4322"),
        C("#3a3418"), C("#ffd700"),
        new[] { C("#16161b"), C("#0f0f13"), C("#16161b") },
        new[] { C("#111115"), C("#17171c"), C("#111115") },
        new[] { C("#101014"), C("#141419"), C("#101014") },
        new[] { C("#111115"), C("#0b0b0f"), C("#09090c"), C("#070709") },
        new[] { C("#ffe14d"), C("#ffd700"), C("#e6c800") },
        Section: C("#141419"),
        Input: C("#131317"),
        CardShadow: "inset 0 1 0 0 #14FFF3C4, 0 0 0 1 #55E6C800, 0 0 7 0 #33FFD700, 0 6 16 0 #90000000",
        CardShadowHover: "inset 0 1 0 0 #22FFF3C4, 0 0 0 1 #88E6C800, 0 0 10 1 #55FFD700, 0 8 20 0 #A0000000");

    public static readonly PumpTheme[] All = { Blue, Gold };

    /// <summary>شناسهٔ ذخیره‌شده ← تم. شناسه‌های تیرهٔ قدیمی به «مشکی و زرد» می‌رسند، بقیه به «آبیِ روشن».</summary>
    public static PumpTheme ById(string? id) =>
        All.FirstOrDefault(t => t.Id == id)
        ?? (id is "obsidian" or "graphite" or "navy" ? Gold : Blue);
}
