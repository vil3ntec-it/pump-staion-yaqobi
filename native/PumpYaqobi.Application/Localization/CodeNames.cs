namespace PumpYaqobi.Application.Localization;

/// <summary>
/// ══ شورا، ث۳ — یک نامِ ثابت برای هر «کد» ═══════════════════════════════════
/// «سه کد هست: کدِ ایمیل، کدِ هشت‌رقمیِ پمپ، کدِ اشتراکِ آفلاین. هر جا که
/// نوشته می‌شوند نامِ ثابت بگیرند.» تا امروز همان سه چیز با شش نام دیده
/// می‌شدند («کدِ پمپ»، «کدِ اپِ کارمندان»، «کدِ هشت‌رقمی»، «کدِ ایمیلی»،
/// «کدِ شش‌رقمی»، «کدِ اشتراک»، «کدِ آفلاین») و کاربر نمی‌دانست کدام کدام است.
///
/// ⛔ هر نوشتهٔ دیدنیِ برنامهٔ کامپیوتر و اپِ گوشی فقط همین سه نام را دارد —
/// `CodeNamesTests` نام‌های کهنه (<see cref="Retired"/>) را در رشته‌های دیدنی
/// قدغن کرده. «کدِ کامپیوتر» چهارمی نیست: ورودیِ ساختنِ کلیدِ بی‌اینترنت است و
/// همان می‌ماند.
/// ⚠️ پنل، بات و نامهٔ ایمیل در ریپوهای دیگرند؛ آن‌جا فقط با پرسش از صاحب ریپو.
/// </summary>
public static class CodeNames
{
    /// <summary>شش رقمی که به ایمیل می‌رود — ثبت‌نام، ورود بی رمز، رمزِ تازه.</summary>
    public const string Email = "کدِ تأییدِ ایمیل";

    /// <summary>هشت رقمِ هر پمپ که گوشیِ کارمند و صاحب یک بار می‌زند.</summary>
    public const string PhoneApp = "کدِ اپِ گوشی";

    /// <summary>برگهٔ امضاشدهٔ اشتراک که بی اینترنت روی یک کامپیوتر کار می‌کند.</summary>
    public const string OfflineKey = "کلیدِ اشتراکِ بی‌اینترنت";

    /// <summary>نام‌های کهنه — هیچ‌کدام دیگر در نوشتهٔ دیدنی نمی‌آید.</summary>
    public static readonly string[] Retired =
    {
        "کدِ پمپ", "کدِ اپِ کارمندان", "کدِ هشت‌رقمی",
        "کدِ ایمیلی", "کدِ ایمیل", "کدِ شش‌رقمی",
        "کدِ اشتراکِ آفلاین", "کدِ اشتراک", "کدِ آفلاین",
    };

    /// <summary>
    /// نخستین نامِ کهنه در این متن — یا null. «کدِ ایمیل» در «کدِ تأییدِ ایمیل»
    /// نیست (کسرهٔ «کدِ» پیش از «ایمیل» نمی‌آید)، پس نامِ تازه هرگز کهنه دیده
    /// نمی‌شود.
    /// </summary>
    public static string? OldNameIn(string? text)
    {
        if (string.IsNullOrEmpty(text)) return null;
        foreach (var old in Retired)
            if (text.Contains(old, StringComparison.Ordinal)) return old;
        return null;
    }
}
