    /// <summary>
    /// معنیِ نخستین واژه‌ای که در این متن آمده (سرستون یا عنوان) — یا null.
    /// ⚠️ واژه‌به‌واژه، نه زیررشته: «فیصدی» در «فی» نمی‌خورد.
    /// </summary>
    public static string? MeaningIn(string? text)
    {
        if (string.IsNullOrWhiteSpace(text)) return null;
        //  به ترتیبِ خودِ متن — «ختمِ پایه» معنیِ «ختم» را می‌دهد، نه «پایه»
        foreach (var raw in text.Split(new[] { ' ', '\u200c', '/', '·', '(', ')', '«', '»', ':', '،', '-', '—', '\n' },
                                       StringSplitOptions.RemoveEmptyEntries))
        {
            var w = raw.TrimEnd('\u0650', '\u0654');   // کسرهٔ اضافه و همزهٔ «ٔ»
            foreach (var t in All)
                if (t.Word == w) return t.Word + ": " + t.Meaning;
        }
        return null;
    }
}
