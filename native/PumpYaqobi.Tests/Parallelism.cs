using Xunit;

//  ══ چرا آزمون‌های این پروژه موازی نمی‌دوند ═══════════════════════════════════
//
//  این سومین بار است که همین یک چیز **ساختِ نسخه را می‌شکند**:
//    • اجرای #۱۲۵ — `ColumnWidthMemoryTests` و `SettingsDurabilityTests`
//    • اجرای #۱۲۸ — `SettingsDurabilityTests` (۳۸ خرابی از ۴۰)
//    • اجرای #۱۳۰ — `AcctLiveTests` عددِ `s18` را دید؛ یعنی `StationCode`ی که
//      `SettingsDurabilityTests` در پوشهٔ **خودش** نوشته بود
//
//  ریشه یکی است و عوض نمی‌شود: `AppSettings.DirOverride` یک متغیرِ **استاتیکِ
//  سراسری** است و xUnit کلاس‌ها را موازی می‌دواند. کلاسی که پوشه را عوض
//  می‌کند، پوشه را برای **همهٔ** کلاس‌هایی که هم‌زمان می‌دوند عوض می‌کند.
//
//  ⛔ **و چرا «نشانِ `[Collection]` را اضافه کن» کافی نبود**: آن نشان فقط
//  کلاسی را می‌پوشاند که کسی **یادش بماند** بگذاردش، و فقط وقتی که آن کلاس
//  نامِ `AppSettings` را **صریح** در خودش داشته باشد. `AcctLiveTests` هیچ‌کدام
//  را نداشت — تنظیمات را از راهِ `AcctLive` **غیرمستقیم** می‌خواند. یعنی
//  فهرستی که با گشتنِ سورس ساخته شود ذاتاً ناقص است.
//
//  پس از امروز کلِ اسمبلی سریال می‌دود. بهایش فقط وقتِ دیوارِ CI است؛
//  سودش این است که «سبز» دوباره معنی می‌دهد. برای برنامه‌ای که قرار است
//  دستِ مشتری برود، آزمونی که گاهی دروغ بگوید از نداشتنش بدتر است.
//
//  ⚠️ این را برای «تندتر شدنِ CI» برنگردانید. اگر روزی واقعاً لازم شد،
//  راهِ درست این است که `DirOverride` از یک متغیرِ استاتیک دربیاید — نه
//  این‌که دوباره به حافظهٔ آدم‌ها تکیه کنیم.

[assembly: CollectionBehavior(DisableTestParallelization = true)]

namespace PumpYaqobi.Tests;

/// <summary>
/// ══ آزمون هیچ‌وقت به تنظیماتِ واقعیِ کاربر دست نمی‌زند ══════════════════════
///
/// کلاسی که خودش پوشه نمی‌دهد، `AppSettings.Dir`ِ پیش‌فرض را می‌خواند — یعنی
/// `%APPDATA%\PumpYaqobi`ِ **خودِ آدمی که آزمون را می‌دواند**. روی رانرِ CI
/// خالی است و کسی نمی‌فهمد، ولی روی کامپیوترِ خودِ صاحب ریپو یعنی آزمون
/// می‌تواند تنظیماتِ واقعی (کدِ پمپ، کلیدِ عمومی، توکن‌ها) را بخواند و
/// بنویسد.
///
/// پس پیش از **هر** آزمونی پوشه به یک جای موقت برده می‌شود. کلاس‌هایی که
/// خودشان پوشه می‌سازند همچنان کارِ خودشان را می‌کنند و سرِ پاک‌سازی به همین
/// برمی‌گردند، نه به `null`.
/// </summary>
internal static class TestSettingsHome
{
    [System.Runtime.CompilerServices.ModuleInitializer]
    internal static void Redirect()
    {
        try
        {
            var dir = Path.Combine(Path.GetTempPath(),
                "pump-tests-" + Guid.NewGuid().ToString("N")[..8]);
            Directory.CreateDirectory(dir);
            PumpYaqobi.App.Services.AppSettings.DirOverride = dir;
        }
        catch { /* نشدنش نباید جلوی دویدنِ آزمون‌ها را بگیرد */ }
    }
}
